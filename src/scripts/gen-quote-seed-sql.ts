// Writes migration-quote-engine-002-seed.sql (and its .down.sql) from the
// seeded rate table, so the database seed can never drift from
// src/quote/seed/rateTable.v1.ts. Run: npx tsx src/scripts/gen-quote-seed-sql.ts

import { writeFileSync } from 'node:fs'
import { rateTableV1 } from '../quote/seed/rateTable.v1.js'
import { CONSENT_EN } from '../quote/seed/consent.js'

const q = (v: unknown) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`)
const j = (v: unknown) => (v === null || v === undefined ? 'NULL' : `${q(JSON.stringify(v))}::jsonb`)

const t = rateTableV1
const rows = Object.values(t.items).map(i => `  (v_id, ${[
  q(i.key), q(i.category), q(i.label), q(i.industry ?? null), q(i.unit),
  i.low ?? 'NULL', i.high ?? 'NULL', q(i.use), i.custom ? 'true' : 'false',
  i.scenes ?? 'NULL', j(i.tiers ?? null), j(i.meta ?? {}),
].join(', ')})`)

const up = `-- Quote engine, migration 002: publish rate table v${t.version} and the consent text.
-- GENERATED by src/scripts/gen-quote-seed-sql.ts from src/quote/seed/rateTable.v1.ts. Do not edit by hand.
-- Rollback: migration-quote-engine-002-seed.down.sql
-- Requires migration-quote-engine-001.sql. Run in the Supabase SQL editor.

BEGIN;

DO $$
DECLARE v_id UUID;
BEGIN
  INSERT INTO public.qe_rate_tables (version, status, effective_from, settings, notes, published_at)
  VALUES (${t.version}, 'published', ${q(t.effectiveFrom)}, ${j(t.settings)}, 'Seeded from docs/rate-card.md (Viewora Pricing & Rate Card 2026)', now())
  RETURNING id INTO v_id;

  INSERT INTO public.qe_rate_items
    (rate_table_id, key, category, label, industry, unit, amount_low, amount_high, use_value, custom, scenes, tiers, meta)
  VALUES
${rows.join(',\n')};
END $$;

INSERT INTO public.qe_consent_texts (locale, body) VALUES ('en', ${q(CONSENT_EN)});

COMMIT;
`

const down = `-- Rollback for migration-quote-engine-002-seed.sql. Removes rate table v${t.version}
-- (its items cascade) and the seeded consent text, if no lead points at it.

BEGIN;
DELETE FROM public.qe_rate_tables WHERE version = ${t.version};
DELETE FROM public.qe_consent_texts c
  WHERE c.body = ${q(CONSENT_EN)}
    AND NOT EXISTS (SELECT 1 FROM public.qe_leads l WHERE l.consent_text_id = c.id);
COMMIT;
`

writeFileSync('src/utils/migration-quote-engine-002-seed.sql', up)
writeFileSync('src/utils/migration-quote-engine-002-seed.down.sql', down)
console.log(`wrote ${rows.length} rate items for v${t.version}`)

